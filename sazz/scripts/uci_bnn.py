"""UCI BNN benchmarks — PDMP samplers vs HMC/NUTS, multi-split aware.

Compares four PDMP samplers (ZigZag, Sticky ZigZag, Boomerang, Sticky
Boomerang) plus optionally NumPyro NUTS on three UCI regression
datasets (Boston, Naval, Energy) and four toy 1D datasets (Hernandez
PBP cubic, gap, sharp, multiscale). All PDMP samplers use PLI thinning.

Metrics: test RMSE (standardised + original units), test mean log-lik,
mean predictive std, and per-coordinate ESS on the resampled chain.

NUTS is OFF by default — pass --include-nuts to run it.

UCI datasets are run on 5 random train/test splits (configurable).
Toy 1D datasets are pre-generated by `sazz.scripts.generate_toys` and
run as a single "split"; this keeps the runner stateless w.r.t. data
generation, and the saved toys are reproducible regardless of unrelated
code changes.

Output layout:
    datasets/toy_1d/
      <toy>.pt                # generated by generate_toys.py; carries config
    results/uci_bnn/
      <dataset>/
        split_<NN>/
          <sampler>.pt        # thinned samples + config + metrics
          metrics.json        # all sampler rows for this split
      metrics.csv             # aggregated across all (dataset, split, sampler)

Workflow:
    # First: generate the toys (one-time setup)
    python -m sazz.scripts.generate_toys

    # Default: PDMPs only, splits 0-4, all UCI datasets
    python -m sazz.scripts.uci_bnn

    # Toy datasets — no splits, single run
    python -m sazz.scripts.uci_bnn --datasets hernandez

    # Mix UCI and toy in one run
    python -m sazz.scripts.uci_bnn --datasets boston hernandez --splits 0

    # Add NUTS as a 5th sampler (slow!)
    python -m sazz.scripts.uci_bnn --datasets hernandez --include-nuts

    # NUTS only on Boston split 0 (one-shot baseline)
    python -m sazz.scripts.uci_bnn --datasets boston --splits 0 \\
                                    --samplers nuts --include-nuts

    # Resume: skip (dataset, split, sampler) combos already on disk
    python -m sazz.scripts.uci_bnn --splits 0 1 2 3 4 --resume

    # Aggregate existing per-split results into metrics.csv (no sampling)
    python -m sazz.scripts.uci_bnn --aggregate-only
"""

