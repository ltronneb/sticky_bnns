def load_toy(name: str, toy_dir: Path = None) -> tuple[dict[str, Any], "BNNConfig"]:
    """Load a pre-generated toy dataset and its inline BNNConfig.

    Toys are produced by `sazz.scripts.generate_toys` and saved to
    `datasets/toy_1d/<name>.pt`. The .pt file contains the standardised
    dataset plus a "config" key holding the BNNConfig used to build the
    BNN target. We pop the config out and return both separately so the
    runner doesn't need to reach into the data dict.

    Raises FileNotFoundError if the toy hasn't been generated yet.
    """
    toy_dir = toy_dir or TOY_DIR
    path = toy_dir / f"{name}.pt"
    if not path.exists():
        raise FileNotFoundError(
            f"Toy dataset '{name}' not found at {path}. "
            f"Run: python -m sazz.scripts.generate_toys --names {name}"
        )
    data = torch.load(path, weights_only=False)
    cfg = data.pop("config")
    return data, cfg


